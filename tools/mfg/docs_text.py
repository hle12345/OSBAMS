def _pin_table(b):
    rows = [["Ref", "Pad", "Net", "Notes"]]
    notes = {("J1", "1"): "12V_IN (+12 V input, before D3)", ("J1", "2"): "GND", ("J2", "1"): "COIL_V (coil +, via E-stop loop)",
             ("J2", "2"): "COIL_SW (coil -, MOSFET drain)", ("J3", "1"): "+12V (E-stop loop in)", ("J3", "2"): "COIL_V (E-stop loop out)",
             ("J4", "1"): "+3V3", ("J4", "2"): "GND", ("J4", "3"): "SCL", ("J4", "4"): "SDA",
             ("J6", "1"): "+3V3", ("J6", "2"): "GND", ("J6", "3"): "UART_TX", ("J6", "4"): "UART_RX",
             ("Q1", "1"): "Gate", ("Q1", "2"): "Drain", ("Q1", "3"): "Source", ("U1", "1"): "NC", ("U1", "2"): "SDA",
             ("U1", "3"): "GND", ("U1", "4"): "SCLK", ("U1", "5"): "VDD (3.3 V)",
             ("C1", "1"): "+ (positive)", ("C1", "2"): "- (negative)",
             ("D1", "1"): "pad 1 = CATHODE (footprint) - on GND  [MISMATCH]", ("D1", "2"): "pad 2 = anode (footprint) - on +12V  [MISMATCH]",
             ("D2", "1"): "pad 1 = CATHODE (footprint) - on COIL_SW  [MISMATCH]", ("D2", "2"): "pad 2 = anode (footprint) - on COIL_V  [MISMATCH]",
             ("D3", "1"): "pad 1 = CATHODE (footprint) - on 12V_IN  [MISMATCH]", ("D3", "2"): "pad 2 = anode (footprint) - on +12V  [MISMATCH]"}
    for f in sorted(b.footprints, key=lambda f: f["ref"]):
        if f["ref"].startswith("MH"):
            continue
        for p in sorted([q for q in f["pads"] if q["num"].isdigit()], key=lambda p: int(p["num"])):
            rows.append([f["ref"], p["num"], (p["net"] or "-").lstrip("/"), notes.get((f["ref"], p["num"]), p["func"])])
    return rows


