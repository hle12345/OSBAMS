def power_tree_figure():
    fig = plt.figure(figsize=(11.69, 8.27))
    ax = fig.add_axes([0.02, 0.05, 0.96, 0.82]); ax.axis("off"); ax.set_xlim(0, 100); ax.set_ylim(0, 60)
    fig.text(0.03, 0.95, "OSBAMS Rev.2 controller PCB - power tree", fontsize=13, fontweight="bold")
    fig.text(0.03, 0.925, "Derived from the netlist. There is NO 5 V rail and NO regulator on this PCB; 3.3 V comes from the Nucleo module.", fontsize=7, color="#a00")
    def box(x, y, w, h, t, fc="#e6eef8"):
        ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.3", fc=fc, ec="#345"))
        ax.text(x + w / 2, y + h / 2, t, ha="center", va="center", fontsize=7)
    def arr(x0, y0, x1, y1, t=""):
        ax.annotate("", (x1, y1), (x0, y0), arrowprops=dict(arrowstyle="->", color="#333"))
        if t: ax.text((x0 + x1) / 2, (y0 + y1) / 2 + 0.8, t, fontsize=6, ha="center", color="#0000aa")
    box(2, 44, 16, 8, "External 12 V supply\n(not on this PCB;\nconnects at J1)", "#f4e6d0")
    box(24, 44, 14, 8, "J1 PWR_IN_12V\n(12V_IN / GND)"); arr(18, 48, 24, 48)
    box(44, 44, 14, 8, "D3 SB560\nreverse-polarity\nSchottky"); arr(38, 48, 44, 48, "12V_IN")
